#!/usr/bin/env python3
"""Two-way Excel bridge for the product catalog.

EXPORT
    python3 data/tools/catalog_xlsx.py export [output.xlsx]
        Writes the full catalog (app/data/catalogData.ts, 1360 products) to an
        Excel workbook with a README sheet, a Products sheet (all editable
        fields) and a Leaves reference sheet.

IMPORT
    python3 data/tools/catalog_xlsx.py import <file.xlsx>
        Reads an edited workbook and applies the changes back onto
        app/data/catalogData.ts. Rows are matched by the `id` column (never
        rename or delete ids). Untouched nested data (photo galleries, specs)
        is preserved as-is.

After an import, restart the dev server / rebuild so the app picks up the
new data, then reload the app.
"""
from __future__ import annotations

import json
import os
import re
import sys
from collections import Counter
from pathlib import Path

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parents[2]
CATALOG_TS = ROOT / "app" / "data" / "catalogData.ts"
LEAVES_TS = ROOT / "app" / "data" / "catalogLeaves.ts"

# Excel column name -> (catalog key, kind)
COLUMNS = [
    ("id", "id", "id"),
    ("name", "n", "text"),
    ("category", "c", "slug"),
    ("subcategory", "sc", "slug"),
    ("subcategory_name", "scn", "text"),
    ("description", "d", "text"),
    ("price_aed", "o", "int"),
    ("list_price_aed", "l", "int"),
    ("discount_percent", "pc", "int"),
    ("labels", "lb", "labels"),
    ("stock_status", "st", "text"),
    ("delivery_days", "dl", "int"),
    ("free_delivery", "fd", "bool"),
    ("free_assembly", "fa", "bool"),
    ("image_url", "remoteImage", "text"),
]
# Excel column name -> (override key, kind). Imported into app/data/catalogOverrides.ts
# and merged on top of the harvested product-page details by the app.
OVERRIDE_COLUMNS = [
    ("gallery_urls", "gallery", "pipe"),
    ("colors", "colors", "colors"),
    ("fabrics", "fabrics", "list"),
    ("dimensions", "dimensions", "rows"),
    ("materials", "material", "rows"),
]
OVERRIDES_TS = ROOT / "app" / "data" / "catalogOverrides.ts"
EDITABLE = [name for name, _, kind in COLUMNS if kind != "id"] + [name for name, _, _ in OVERRIDE_COLUMNS]


def parse_ts_array(path: Path):
    """Parse `export const x = [ ... ] as const;` files (JSON-ish bodies)."""
    text = path.read_text(encoding="utf-8")
    body = text[text.index("[") : text.rindex("]") + 1]
    return json.loads(re.sub(r",\s*([\]}])", r"\1", body))


def write_catalog_ts(products: list[dict]) -> None:
    text = "export const catalogData = " + json.dumps(products, indent=2, ensure_ascii=False) + " as const;\n"
    CATALOG_TS.write_text(text, encoding="utf-8")
    touch_detail_module()


def touch_detail_module() -> None:
    """Bump productDetails.ts's mtime so the dev bundler re-reads its imports
    (some watchers miss rewrites of files created after startup)."""
    target = CATALOG_TS.parent / "productDetails.ts"
    if target.exists():
        os.utime(target, None)


def norm_text(value: str) -> str:
    """Excel normalizes CRLF line endings in cells on save — compare normalized."""
    return value.replace("\r\n", "\n")


def parse_overrides_ts() -> dict:
    text = OVERRIDES_TS.read_text(encoding="utf-8")
    anchor = text.index("catalogOverrides")
    body = text[text.index("{", anchor) : text.rindex("}") + 1]
    return json.loads(re.sub(r",\s*([\]}])", r"\1", body))


def write_overrides_ts(overrides: dict) -> None:
    header = (
        "/**\n"
        " * Sheet-driven overrides merged on top of the harvested product details.\n"
        " *\n"
        " * Generated by `data/tools/catalog_xlsx.py import` from the extra Excel\n"
        " * columns (gallery_urls, colors, fabrics, dimensions, materials). Keys are\n"
        " * catalogue product ids; every list is optional and may be empty.\n"
        " */\n"
        "export type CatalogOverride = {\n"
        "  /** Extra gallery images — absolute https URLs or PRODUCT_IMAGE_BASE-relative paths. */\n"
        "  gallery?: string[];\n"
        "  /** Colour swatches. A name that already exists on the product is updated in place. */\n"
        "  colors?: { name: string; hex?: string; image?: string }[];\n"
        "  /** Extra fabric names. */\n"
        "  fabrics?: string[];\n"
        "  /** Rows merged into (or added as) named info sections, e.g. \"dimensions\". */\n"
        "  sections?: { name: string; rows: { label: string; value: string }[] }[];\n"
        "};\n\n"
    )
    text = header + "export const catalogOverrides: Record<string, CatalogOverride> = " + json.dumps(overrides, indent=2, ensure_ascii=False) + ";\n"
    OVERRIDES_TS.write_text(text, encoding="utf-8")


def coerce(kind: str, value, excel_name: str):
    if kind == "int":
        if value in (None, ""):
            raise ValueError(f"{excel_name}: price/count cells cannot be empty")
        num = float(value)
        if num != int(num) or num < 0:
            raise ValueError(f"{excel_name}: expected a whole number >= 0, got {value!r}")
        return int(num)
    if kind == "bool":
        num = 1 if value in (1, "1", True, "yes", "true") else 0
        return num
    if kind == "labels":
        if value in (None, ""):
            return []
        return [part.strip() for part in str(value).split(",") if part.strip()]
    if kind == "pipe":
        if value in (None, ""):
            return []
        return [part.strip() for part in str(value).split("|") if part.strip()]
    if kind == "list":
        if value in (None, ""):
            return []
        return [part.strip() for part in str(value).split(",") if part.strip()]
    if kind == "colors":
        if value in (None, ""):
            return []
        colors = []
        for entry in str(value).split("|"):
            entry = entry.strip()
            if not entry:
                continue
            match = re.match(r"^(.*?)\s*(#[0-9a-fA-F]{6})?\s*(https?://\S+)?$", entry)
            name = (match.group(1) or "").strip() if match else entry
            hex_value = (match.group(2) or "").strip() if match else ""
            image = (match.group(3) or "").strip() if match else ""
            if not name:
                raise SystemExit(f"{excel_name}: colour entry {entry!r} needs a name, e.g. `Beige #D8C7B0`")
            color = {"name": name}
            if hex_value:
                color["hex"] = hex_value
            if image:
                color["image"] = image
            colors.append(color)
        return colors
    if kind == "rows":
        if value in (None, ""):
            return []
        rows = []
        for entry in str(value).split("|"):
            entry = entry.strip()
            if not entry:
                continue
            if ":" not in entry:
                raise SystemExit(f"{excel_name}: entry {entry!r} must look like `Label: value` (separate rows with |)")
            label, row_value = entry.split(":", 1)
            rows.append({"label": label.strip(), "value": row_value.strip()})
        return rows
    text = "" if value is None else str(value)
    return norm_text(text)


def sheet_products(ws, products, overrides: dict | None = None) -> None:
    overrides = overrides or {}
    header_fill = PatternFill("solid", fgColor="DA1921")
    rich_fill = PatternFill("solid", fgColor="282984")
    id_fill = PatternFill("solid", fgColor="DDDDDD")
    override_names = {name for name, _, _ in OVERRIDE_COLUMNS}
    for col, (name, _, _) in enumerate(COLUMNS + OVERRIDE_COLUMNS, start=1):
        cell = ws.cell(row=1, column=col, value=name)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = id_fill if name == "id" else (rich_fill if name in override_names else header_fill)
    for row, product in enumerate(products, start=2):
        override = overrides.get(product["id"], {})
        for col, (name, key, kind) in enumerate(COLUMNS, start=1):
            value = product.get(key)
            if kind == "labels":
                value = ", ".join(value or [])
            ws.cell(row=row, column=col, value=value)
        for col, (name, key, kind) in enumerate(OVERRIDE_COLUMNS, start=len(COLUMNS) + 1):
            if key in ("dimensions", "material"):
                value = next((s["rows"] for s in override.get("sections", []) if s["name"] == key), None)
            else:
                value = override.get(key)
            if value is None:
                continue
            if kind == "list":
                value = ", ".join(value)
            elif kind == "pipe":
                value = " | ".join(value)
            elif kind == "colors":
                value = " | ".join(
                    entry["name"] + ((" " + entry["hex"]) if entry.get("hex") else "") + ((" " + entry["image"]) if entry.get("image") else "")
                    for entry in value
                )
            elif kind == "rows":
                value = " | ".join(f"{row['label']}: {row['value']}" for row in value)
            ws.cell(row=row, column=col, value=value)
    widths = [34, 38, 14, 16, 16, 70, 11, 14, 11, 24, 13, 9, 10, 10, 60, 60, 40, 20, 50, 50]
    for col, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(COLUMNS) + len(OVERRIDE_COLUMNS))}{len(products) + 1}"
    for row in ws.iter_rows(min_row=2, min_col=6, max_col=6):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")


