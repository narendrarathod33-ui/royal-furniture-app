#!/usr/bin/env node
/**
 * Builds app/data/colorSwatches.ts from harvest/product-details.json.
 *
 * Unlike harvest/build-product-details.py (which caps colors at 8 and keeps
 * "Selectable" placeholders), this table keeps ALL real color swatches (e.g.
 * all 11 shades on customizable sofas), binds each swatch's fabric from its SKU,
 * and drops invalid hex codes while compacting via an interned string table (~58 KB).
 *
 * Usage: node scripts/build-color-swatches.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCE = resolve(ROOT, 'harvest/product-details.json');
const TARGET = resolve(ROOT, 'app/data/colorSwatches.ts');

function inferFabricFromSku(sku, fabrics) {
  const lowerSku = (sku || '').toLowerCase();
  if (!lowerSku) return '';
  for (const raw of fabrics || []) {
    const clean = String(raw || '').trim();
    if (!clean || clean.toLowerCase() === 'fabric') continue;
    const token = `-${clean.toLowerCase().replace(/\s+/g, '-')}-`;
    if (lowerSku.includes(token)) return clean;
  }
  return '';
}

export function buildSwatchModule(harvestData) {
  const details = harvestData?.details || {};
  const T = [];
  const index = new Map();
  const intern = (value) => {
    const clean = value == null ? '' : String(value).trim();
    if (!clean) return -1;
    if (!index.has(clean)) {
      index.set(clean, T.length);
      T.push(clean);
    }
    return index.get(clean);
  };

  const records = {};
  for (const slug of Object.keys(details).sort()) {
    const det = details[slug];
    if (!det || typeof det !== 'object' || det.error) continue;
    const fabrics = Array.isArray(det.fabrics) ? det.fabrics : [];
    const seen = new Set();
    const rows = [];

    for (const color of det.colors || []) {
      const name = String(color?.n || '').trim();
      if (!name || /^selectable$/i.test(name)) continue;
      const hex = /^#[0-9a-f]{6}$/i.test(String(color?.hex || '').trim())
        ? String(color.hex).trim().toUpperCase()
        : '';
      const fabric = inferFabricFromSku(color?.sku, fabrics);
      const image = color?.img ? String(color.img).trim() : '';
      const stock = color?.stock ? String(color.stock).trim() : '';
      const key = `${fabric.toLowerCase()}|${name.toLowerCase()}`;
      if (seen.has(key)) continue;
      seen.add(key);

      rows.push([
        intern(name),
        intern(hex),
        intern(fabric),
        intern(image),
        intern(stock),
      ]);
    }

    if (rows.length) records[slug] = rows;
  }

  return `/**
 * Complete real color & fabric swatch catalog extracted from harvest/product-details.json.
 * Generated by \`node scripts/build-color-swatches.mjs\` — do not hand-edit.
 *
 * Strips "Selectable" placeholders and keeps all swatches (e.g. all 11 shades per sofa)
 * along with fabric bindings inferred from swatch SKUs and stock status.
 */
import { slugFromProductId } from './officialSizes';
import type { RawSwatchInput } from '../../utils/colorVariants';

// Tuple: [nameIdx, hexIdx, fabricIdx, imageIdx, stockIdx]
type RawSwatchTuple = readonly [number, number, number, number, number];

const T: readonly string[] = ${JSON.stringify(T)};

const SWATCHES: Record<string, readonly RawSwatchTuple[]> = {
${Object.entries(records)
  .map(([slug, rows]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(rows)},`)
  .join('\n')}
};

export function getColorSwatches(productId: string): RawSwatchInput[] {
  const slug = slugFromProductId(productId);
  const rows = SWATCHES[slug] || SWATCHES[slug.replace(/-[0-9a-f]{6}$/, '')];
  if (!rows) return [];
  return rows.map(([nameIdx, hexIdx, fabricIdx, imageIdx, stockIdx]) => ({
    name: T[nameIdx],
    hex: hexIdx >= 0 ? T[hexIdx] : undefined,
    fabric: fabricIdx >= 0 ? T[fabricIdx] : undefined,
    image: imageIdx >= 0 ? T[imageIdx] : undefined,
    stock: stockIdx >= 0 ? T[stockIdx] : undefined,
  }));
}

export const SWATCH_PRODUCT_COUNT = ${Object.keys(records).length};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const harvest = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const output = buildSwatchModule(harvest);
  writeFileSync(TARGET, output, 'utf8');
  console.log(`Wrote ${TARGET} (${(Buffer.byteLength(output) / 1024).toFixed(1)} KB)`);
}
